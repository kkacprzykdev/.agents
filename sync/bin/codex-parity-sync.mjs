#!/usr/bin/env node

// Stopgap until sync parity (kkacprzykdev/.agents#2): gives Codex the commands and rules that ag sync links only
// into Claude and Cursor. It reads them from the links ag sync made in ~/.claude, generates Codex files into
// sync/.generated/codex/, and links those into ~/.codex. Nothing in ag runs it: ag-codex-parity.mjs, linked as
// `ag` ahead of the real one on PATH, runs it after every ag command that syncs. See ADR 0029.

import {
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  readlinkSync,
  realpathSync,
  renameSync,
  rmSync,
  symlinkSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { spawnSync } from "node:child_process";
import { basename, dirname, join, relative, resolve, sep } from "node:path";
import { homedir } from "node:os";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const STORE_ROOT = findStoreRoot();
const GENERATED = join(STORE_ROOT, "sync", ".generated", "codex");
const HOME = homedir();
const CLAUDE_HOME = join(HOME, ".claude");
const CODEX_HOME = join(HOME, ".codex");
const CODEX_SKILLS = join(CODEX_HOME, "skills");
const OVERRIDE = "AGENTS.override.md";
const PREFIX = "cmd-";
const HEADER = "<!-- Generated by codex-parity-sync from the ~/.agents store. The next ag sync rewrites it. -->";

// The same store root as ag: the main checkout, also when this file runs from the Edit worktree.
function findStoreRoot() {
  const fallback = resolve(__dirname, "..", "..");
  const result = spawnSync("git", ["rev-parse", "--path-format=absolute", "--git-common-dir"], {
    cwd: fallback,
    encoding: "utf8",
  });
  return result.status === 0 ? realpathSync(dirname(result.stdout.trim())) : fallback;
}

function display(path) {
  return path === HOME || path.startsWith(`${HOME}${sep}`) ? `~${path.slice(HOME.length)}` : path;
}

function log(message) {
  console.log(`codex-parity-sync: ${message}`);
}

// Taken by a file, a folder, or a link, even a broken one.
function occupied(path) {
  return existsSync(path) || isLink(path);
}

function isLink(path) {
  try {
    return lstatSync(path).isSymbolicLink();
  } catch {
    return false;
  }
}

// A link this script made: it points into sync/.generated/codex/.
function isOwnLink(path) {
  if (!isLink(path)) {
    return false;
  }
  const target = relative(GENERATED, resolve(dirname(path), readlinkSync(path)));
  return target !== "" && !target.startsWith("..") && !target.startsWith(sep);
}

// The store files behind the links ag sync made in one Claude target folder, sorted by link name.
function linkedSources(folder) {
  const dir = join(CLAUDE_HOME, folder);
  if (!existsSync(dir)) {
    return [];
  }
  return readdirSync(dir)
    .filter((name) => name.endsWith(".md") && isLink(join(dir, name)) && existsSync(join(dir, name)))
    .sort()
    .map((name) => ({ name: basename(name, ".md"), source: realpathSync(join(dir, name)) }));
}

// Like Claude: the frontmatter description, else the first non-empty body line, without its heading marks.
function describe(text) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n?---\r?\n?/);
  const frontmatter = match ? match[1] : "";
  const body = match ? text.slice(match[0].length) : text;
  const fromFrontmatter = frontmatter.match(/^description:[ \t]*(.*)$/m)?.[1].trim().replace(/^(["'])(.*)\1$/, "$2");
  if (fromFrontmatter) {
    return fromFrontmatter;
  }
  const line = body.split(/\r?\n/).find((entry) => entry.trim());
  return line ? line.replace(/^#+\s*/, "").trim() : "";
}

function commandSkill({ name, source }) {
  const description = describe(readFileSync(source, "utf8")) || `The ${name} command.`;
  return [
    "---",
    `name: ${name}`,
    `description: ${JSON.stringify(description)}`,
    "---",
    "",
    HEADER,
    "",
    `This skill is the store command \`${name}\`. Read \`${source}\` in full and follow it as your instructions. The text the user wrote after \`$${name}\` is the command's input.`,
    "",
  ].join("\n");
}

function overrideFile(rules) {
  const agents = join(CODEX_HOME, "AGENTS.md");
  const lines = [
    HEADER,
    "",
    "# Global instructions",
    "",
    "Codex loads this file in place of `~/.codex/AGENTS.md`, so the global instructions live in the files below. Before your first reply in a session, read each file in full and follow it as if its text stood here.",
    "",
  ];
  if (existsSync(agents)) {
    lines.push(`- \`${agents}\`: the global instructions.`);
  }
  if (rules.length) {
    lines.push("- Rules. Each rule's frontmatter (`description`, `globs`, `paths`, `alwaysApply`) says when it applies:");
    lines.push(...rules.map(({ source }) => `  - \`${source}\``));
  }
  lines.push("");
  return lines.join("\n");
}

// Every name Codex lists as a skill besides the command skills: ~/.codex/skills and the third-party ~/.agents/skills.
function otherSkillNames() {
  const names = new Set();
  for (const dir of [CODEX_SKILLS, join(STORE_ROOT, "skills")]) {
    if (!existsSync(dir)) {
      continue;
    }
    for (const name of readdirSync(dir)) {
      if (!name.startsWith(".") && !isOwnLink(join(dir, name))) {
        names.add(name);
      }
    }
  }
  return names;
}

function removeOwnLinks() {
  let removed = 0;
  const paths = existsSync(CODEX_SKILLS) ? readdirSync(CODEX_SKILLS).map((name) => join(CODEX_SKILLS, name)) : [];
  for (const path of [...paths, join(CODEX_HOME, OVERRIDE)]) {
    if (isOwnLink(path)) {
      unlinkSync(path);
      removed += 1;
    }
  }
  return removed;
}

function writeGenerated(commands, rules) {
  const next = `${GENERATED}.next`;
  rmSync(next, { recursive: true, force: true });
  for (const command of commands) {
    const dir = join(next, "skills", `${PREFIX}${command.name}`);
    mkdirSync(join(dir, "agents"), { recursive: true });
    writeFileSync(join(dir, "SKILL.md"), commandSkill(command));
    writeFileSync(join(dir, "agents", "openai.yaml"), "policy:\n  allow_implicit_invocation: false\n");
  }
  mkdirSync(next, { recursive: true });
  if (rules.length || existsSync(join(CODEX_HOME, "AGENTS.md"))) {
    writeFileSync(join(next, OVERRIDE), overrideFile(rules));
  }
  rmSync(GENERATED, { recursive: true, force: true });
  renameSync(next, GENERATED);
}

function remove() {
  const removed = removeOwnLinks();
  rmSync(GENERATED, { recursive: true, force: true });
  log(`removed ${removed} link(s) and ${display(GENERATED)}.`);
}

function run() {
  if (!existsSync(CODEX_HOME)) {
    log(`${display(CODEX_HOME)} does not exist, so there is nothing to do.`);
    return;
  }
  if (!existsSync(CLAUDE_HOME)) {
    throw new Error(`it reads commands and rules from the links ag sync makes in ${display(CLAUDE_HOME)}, which does not exist.`);
  }
  const override = join(CODEX_HOME, OVERRIDE);
  if (occupied(override) && !isOwnLink(override)) {
    throw new Error(`${display(override)} was not made by this script, so it changed nothing. Move that file away and rerun.`);
  }

  const commands = linkedSources("commands");
  const rules = linkedSources("rules");
  writeGenerated(commands, rules);
  removeOwnLinks();

  mkdirSync(CODEX_SKILLS, { recursive: true });
  const others = otherSkillNames();
  let linked = 0;
  for (const { name } of commands) {
    const link = join(CODEX_SKILLS, `${PREFIX}${name}`);
    if (occupied(link)) {
      log(`warning: ${display(link)} already exists and is not a link of this script, so the command ${name} is not linked.`);
      continue;
    }
    symlinkSync(join(GENERATED, "skills", `${PREFIX}${name}`), link, "dir");
    linked += 1;
    if (others.has(name)) {
      log(`warning: the command ${name} and a skill share that name, so Codex lists two skills named ${name}.`);
    }
  }
  if (existsSync(join(GENERATED, OVERRIDE))) {
    symlinkSync(join(GENERATED, OVERRIDE), override);
  }

  log(
    `linked ${linked} command skill(s) into ${display(CODEX_SKILLS)}` +
      (existsSync(override) ? `, and ${display(override)} with ${rules.length} rule(s).` : "."),
  );
}

try {
  if (process.argv.includes("--remove")) {
    remove();
  } else {
    run();
  }
} catch (error) {
  console.error(`codex-parity-sync: error: ${error.message}`);
  process.exit(1);
}
